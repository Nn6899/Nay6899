/** Private-use letter blocks (fraktur, double-struck, script). */
export function styledLetter(code: number): string | null {
  const letter = (offset: number) =>
    offset < 26 ? String.fromCharCode(65 + offset) : offset < 52 ? String.fromCharCode(97 + offset - 26) : null;
  if (code >= 0xf000 && code <= 0xf033) {
    const l = letter(code - 0xf000);
    return l ? `\\mathfrak{${l}}` : null;
  }
  if (code >= 0xf080 && code <= 0xf0b3) {
    const l = letter(code - 0xf080);
    return l ? `\\mathbb{${l}}` : null;
  }
  if (code >= 0xf0c0 && code <= 0xf0c9) return `\\mathbb{${code - 0xf0c0}}`;
  if (code >= 0xf100 && code <= 0xf119) return `\\mathcal{${String.fromCharCode(65 + code - 0xf100)}}`;
  if (code >= 0xf11a && code <= 0xf133) return `\\mathit{${String.fromCharCode(97 + code - 0xf11a)}}`;
  // Unicode Mathematical Alphanumeric Symbols (double-struck A–Z / a–z)
  if (code >= 0x1d538 && code <= 0x1d56b) {
    const l = letter(code - 0x1d538);
    return l ? `\\mathbb{${l}}` : null;
  }
  return null;
}

/**
 * Spacing characters written with the fnSPACE typeface. MTEF v5 uses
 * MTCode 0xEF00–0xEF08; Equation Editor 3 (v3) uses 0xEB00–0xEB08. The low
 * byte selects the width in both cases.
 */
export function spaceLatex(code: number): string | null {
  const hi = code & 0xff00;
  if (hi !== 0xef00 && hi !== 0xeb00) return null;
  switch (code & 0xff) {
    case 0x00: // alignment mark
    case 0x01: // zero-width space
      return '';
    case 0x02: // thin
      return '\\,';
    case 0x03: // medium
      return '\\:';
    case 0x04: // thick
      return '\\;';
    case 0x05: // em
      return '\\quad';
    case 0x06: // 2 em
      return '\\qquad';
    case 0x08: // 1 pt
      return '\\,';
    default:
      return '\\,';
  }
}

