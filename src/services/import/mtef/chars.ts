/** Decode a font position when no MTCode was written. */
export function fontPositionToUnicode(pos: number, symbolFont: boolean): number {
  if (symbolFont) {
    if (pos >= 0x20 && pos <= 0x7e) return SYMBOL_FONT[pos - 0x20];
    if (pos >= 0xa0 && pos <= 0xfe) return SYMBOL_FONT_HIGH[pos - 0xa0];
    return 0;
  }
  if (pos >= 0x80 && pos <= 0x9f) return CP1252_HIGH[pos - 0x80];
  return pos;
}
